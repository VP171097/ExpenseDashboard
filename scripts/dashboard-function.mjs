// Builds supabase/dashboard/ask-tally.ts: the ask-tally function as ONE file, for pasting into the
// Supabase dashboard editor. Run after changing either source file: npm run dashboard-function
import { readFileSync, writeFileSync } from 'node:fs'
const shared = readFileSync('supabase/functions/_shared/tally-ai.ts', 'utf8').replace(/^export /gm, '')
const fn = readFileSync('supabase/functions/ask-tally/index.ts', 'utf8').replace(/^import .*'\.\.\/_shared\/tally-ai\.ts'\n/m, '')
const cut = fn.indexOf('\nconst cors')
writeFileSync('supabase/dashboard/ask-tally.ts', `// ask-tally as ONE file, for pasting into the Supabase dashboard (Edge Functions → Deploy a new function → Via editor).
// Generated by scripts/dashboard-function.mjs from supabase/functions/ask-tally/index.ts and
// supabase/functions/_shared/tally-ai.ts. Edit those, not this file.
${fn.slice(0, cut)}

// ---------- shared request builder ----------
${shared}
// ---------- the function ----------${fn.slice(cut)}`)
console.log('wrote supabase/dashboard/ask-tally.ts')
